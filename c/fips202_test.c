/* FIPS202 KAT: compare C SHAKE vs Python hashlib vectors. */
#include <stdio.h>
#include <string.h>
#include "fips202.h"

int main(void) {
    /* Empty input vectors from FIPS 202 / known answers:
       SHAKE128("",32) and SHAKE256("",64) checked against Python at build time.
       We hardcode expected bytes generated by CPython hashlib (verified below). */
    unsigned char out[64];
    int i, fails = 0;
    /* generated via: hashlib.shake_128(b'').digest(32) etc. */
    static const unsigned char exp128[32] = {
        0x7f,0x9c,0x2b,0xa4,0xe8,0x8f,0x82,0x7d,0x61,0x60,0x45,0x50,0x76,0x05,0x85,0x3e,
        0xd7,0x3b,0x80,0x93,0xf6,0xef,0xbc,0x88,0xeb,0x1a,0x6e,0xac,0xfa,0x66,0xef,0x26
    };
    static const unsigned char exp256_abc[64] = {
        0x48,0x33,0x66,0x60,0x13,0x60,0xa8,0x77,0x1c,0x68,0x63,0x08,0x0c,0xc4,0x11,0x4d,
        0x8d,0xb4,0x45,0x30,0xf8,0xf1,0xe1,0xee,0x4f,0x94,0xea,0x37,0xe7,0x8b,0x57,0x39,
        0xd5,0xa1,0x5b,0xef,0x18,0x6a,0x53,0x86,0xc7,0x57,0x44,0xc0,0x52,0x7e,0x1f,0xaa,
        0x9f,0x87,0x26,0xe4,0x62,0xa1,0x2a,0x4f,0xeb,0x06,0xbd,0x88,0x01,0xe7,0x51,0xe4
    };
    (void)exp256_abc;
    rmdq_shake128(out, 32, (const unsigned char *)"", 0);
    if (memcmp(out, exp128, 32) != 0) {
        printf("FAIL shake128 empty\n got: ");
        for (i=0;i<32;i++) printf("%02x", out[i]);
        printf("\n");
        fails++;
    } else printf("shake128 empty ok\n");

    /* abc vector for shake256(abc,64): compute and print (checked against python in test script) */
    rmdq_shake256(out, 64, (const unsigned char *)"abc", 3);
    if (memcmp(out, exp256_abc, 64) != 0) {
        printf("FAIL shake256 abc\n got: ");
        for (i=0;i<64;i++) printf("%02x", out[i]);
        printf("\n");
        fails++;
    } else printf("shake256 abc ok\n");

    /* multi-block regression: shake128(abc,1024) spans 7 blocks; first/last
     * 32B pinned from CPython hashlib (guards squeeze pointer/index logic). */
    {
        static unsigned char big[1024];
        static const unsigned char exp_head[32] = {
            0x58,0x81,0x09,0x2d,0xd8,0x18,0xbf,0x5c,0xf8,0xa3,0xdd,0xb7,0x93,0xfb,0xcb,0xa7,
            0x40,0x97,0xd5,0xc5,0x26,0xa6,0xd3,0x5f,0x97,0xb8,0x33,0x51,0x94,0x0f,0x2c,0xc8
        };
        static const unsigned char exp_tail[32] = {
            0x2a,0x6c,0xfe,0x22,0x37,0xdf,0xde,0x3a,0x28,0x39,0xf1,0x8f,0x6b,0x96,0x0c,0xdc,
            0x47,0x87,0xa0,0x2b,0xce,0x73,0xea,0x04,0x61,0x5e,0xab,0xef,0xce,0xa5,0xc6,0xc1
        };
        rmdq_shake128(big, 1024, (const unsigned char *)"abc", 3);
        if (memcmp(big, exp_head, 32) != 0 || memcmp(big + 992, exp_tail, 32) != 0) {
            printf("FAIL shake128 multi-block\n");
            fails++;
        } else printf("shake128 multi-block ok\n");
    }

    return fails ? 1 : 0;
}
